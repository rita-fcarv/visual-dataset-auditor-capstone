import argparse
import csv
import os
from itertools import combinations


RELATED_VARIANTS = {
    "original",
    "exact",
    "bright",
    "blur",
    "resized",
}


def get_group_and_variant(filename):
    name = os.path.splitext(filename)[0]
    group, variant = name.rsplit("_", 1)
    return group, variant


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--input",
        default="data/robustness",
        help="Directory containing validation images",
    )
    parser.add_argument(
        "--report",
        default="results/robustness/similarity_report.csv",
        help="Similarity report generated by the CUDA auditor",
    )
    args = parser.parse_args()

    filenames = sorted(
        name
        for name in os.listdir(args.input)
        if name.lower().endswith(".ppm")
    )

    if len(filenames) < 2:
        parser.error("At least two images are required.")

    # Construct ground truth from the controlled dataset.
    expected_pairs = set()

    for first, second in combinations(filenames, 2):
        group_a, variant_a = get_group_and_variant(first)
        group_b, variant_b = get_group_and_variant(second)

        if (
            group_a == group_b
            and variant_a in RELATED_VARIANTS
            and variant_b in RELATED_VARIANTS
        ):
            expected_pairs.add((first, second))

    # Read detected pairs.
    detected_pairs = set()

    with open(args.report, newline="") as file:
        reader = csv.DictReader(file)

        required_columns = {
            "image_1",
            "image_2",
            "hamming_distance",
        }

        if not required_columns.issubset(reader.fieldnames or []):
            raise ValueError("Similarity CSV has missing columns.")

        for row in reader:
            first = row["image_1"]
            second = row["image_2"]

            if first == second:
                raise ValueError("Self-pair found in similarity report.")

            pair = tuple(sorted((first, second)))

            if pair in detected_pairs:
                raise ValueError(f"Duplicate report entry: {pair}")

            detected_pairs.add(pair)

    # Validate that the report only references known images.
    known_files = set(filenames)

    for first, second in detected_pairs:
        if first not in known_files or second not in known_files:
            raise ValueError(
                f"Unknown image in report: {first}, {second}"
            )

    true_positives = expected_pairs & detected_pairs
    false_positives = detected_pairs - expected_pairs
    false_negatives = expected_pairs - detected_pairs

    total_pairs = len(filenames) * (len(filenames) - 1) // 2
    true_negatives = (
        total_pairs
        - len(true_positives)
        - len(false_positives)
        - len(false_negatives)
    )

    tp = len(true_positives)
    fp = len(false_positives)
    fn = len(false_negatives)
    tn = true_negatives

    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0

    f1 = (
        2 * precision * recall / (precision + recall)
        if precision + recall
        else 0.0
    )

    print("\n=== Similarity Detection Evaluation ===")
    print(f"Images:               {len(filenames)}")
    print(f"Total possible pairs: {total_pairs}")
    print(f"Expected pairs:       {len(expected_pairs)}")
    print(f"Detected pairs:       {len(detected_pairs)}")
    print()
    print(f"True positives:       {tp}")
    print(f"False positives:      {fp}")
    print(f"False negatives:      {fn}")
    print(f"True negatives:       {tn}")
    print()
    print(f"Precision:            {precision:.4f}")
    print(f"Recall:               {recall:.4f}")
    print(f"F1 score:             {f1:.4f}")

    if false_positives:
        print("\nFirst 10 false positives:")
        for first, second in sorted(false_positives)[:10]:
            print(f"  {first} <-> {second}")

    if false_negatives:
        print("\nFirst 10 false negatives:")
        for first, second in sorted(false_negatives)[:10]:
            print(f"  {first} <-> {second}")


if __name__ == "__main__":
    main()
